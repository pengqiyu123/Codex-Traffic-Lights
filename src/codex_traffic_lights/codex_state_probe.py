@dataclass(frozen=True)
class SchemaEvidence:
    """Status-related values generated by `codex app-server generate-ts`."""

    thread_status_types: tuple[str, ...]
    thread_active_flags: tuple[str, ...]
    turn_statuses: tuple[str, ...]


@dataclass(frozen=True)
class ProductStateCandidate:
    """Evidence-backed product-facing traffic-light state candidate."""

    name: str
    evidence: str
    confidence: str
    note: str


def extract_thread_status_types(source: str) -> list[str]:
    """Extract ThreadStatus `type` variants from generated TypeScript text."""
    return _dedupe(match.group("value") for match in THREAD_STATUS_RE.finditer(source))


def extract_string_union_values(source: str, type_name: str) -> list[str]:
    """Extract string values from a generated TypeScript string-literal union."""
    pattern = re.compile(STRING_UNION_RE_TEMPLATE.format(name=re.escape(type_name)), re.DOTALL)
    match = pattern.search(source)
    if match is None:
        return []
    return _dedupe(item.group("value") for item in STRING_LITERAL_RE.finditer(match.group("body")))


def collect_schema_evidence(schema_dir: Path) -> SchemaEvidence:
    """Collect traffic-light-relevant status axes from generated TypeScript files."""
    v2_dir = schema_dir / "v2"
    thread_status = _read_text(v2_dir / "ThreadStatus.ts")
    thread_active_flag = _read_text(v2_dir / "ThreadActiveFlag.ts")
    turn_status = _read_text(v2_dir / "TurnStatus.ts")
    return SchemaEvidence(
        thread_status_types=tuple(extract_thread_status_types(thread_status)),
        thread_active_flags=tuple(
            extract_string_union_values(thread_active_flag, "ThreadActiveFlag")
        ),
        turn_statuses=tuple(extract_string_union_values(turn_status, "TurnStatus")),
    )


