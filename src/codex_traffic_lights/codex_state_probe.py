import re
import shutil
import subprocess
import tempfile
import time
from collections.abc import Iterable, Mapping
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

from codex_traffic_lights.state_mapper import CodexStateMapper

THREAD_STATUS_RE = re.compile(r'\{\s*"type"\s*:\s*"(?P<value>[^"]+)"')
STRING_UNION_RE_TEMPLATE = r"export\s+type\s+{name}\s*=\s*(?P<body>[^;]+);"
STRING_LITERAL_RE = re.compile(r'"(?P<value>[^"]+)"')

